function generateHistorical24h(baseAQI: number): HistoricalReading[] {
  const readings: HistoricalReading[] = [];
  const now = new Date('2026-10-10T12:00:00Z');

  for (let i = 23; i >= 0; i--) {
    const time = new Date(now.getTime() - i * 60 * 60 * 1000);
    const hour = time.getUTCHours();
    
    // Diurnal rush hour variations: peaks around 8am and 7pm UTC
    const diurnalFactor =
      1 +
      0.22 * Math.sin(((hour - 8) * Math.PI) / 12) +
      0.15 * Math.sin(((hour - 19) * Math.PI) / 8);
    const noise = (Math.sin(i * 1.7) * 0.08);
    const aqi = Math.max(12, Math.round(baseAQI * diurnalFactor * (1 + noise)));

    const pm25 = parseFloat(((aqi * 0.48) + Math.sin(i) * 3).toFixed(1));
    const pm10 = parseFloat(((pm25 * 1.6) + Math.cos(i) * 5).toFixed(1));
    const no2 = parseFloat(((aqi * 0.28) + Math.sin(i * 2) * 4).toFixed(1));
    const so2 = parseFloat((8.5 + Math.sin(i) * 2.5).toFixed(1));
    const co = parseFloat((0.6 + (aqi / 150) * 0.5).toFixed(2));
    const o3 = parseFloat(((30 + Math.sin(((hour - 14) * Math.PI) / 12) * 25)).toFixed(1));

    readings.push({
      timestamp: time.toISOString(),
      timeLabel: `${hour.toString().padStart(2, '0')}:00`,
      aqi,
      pm25,
      pm10,
      no2,
      so2,
      co,
      o3,
      temperature: Math.round(18 + Math.sin(((hour - 14) * Math.PI) / 12) * 6),
      humidity: Math.round(55 + Math.cos(((hour - 14) * Math.PI) / 12) * 20),
    });
  }

  return readings;
}

function generateForecastPoints(
  baseAQI: number,
  count: number,
  intervalHours: number = 1
): ForecastPoint[] {
  const points: ForecastPoint[] = [];
  const start = new Date('2026-10-10T13:00:00Z');

  for (let i = 0; i < count; i++) {
    const time = new Date(start.getTime() + i * intervalHours * 60 * 60 * 1000);
    const hour = time.getUTCHours();
    
    // Gradual weather shift simulation
    const drift = Math.sin(i / 6) * 18 - (i * 0.2);
    const diurnal = Math.sin(((hour - 8) * Math.PI) / 12) * 14;
    const predictedAQI = Math.max(15, Math.round(baseAQI + drift + diurnal));

    // Uncertainty grows with forecast horizon
    const horizonError = Math.round(5 + (i * 0.75));
    const lowerBound = Math.max(8, predictedAQI - horizonError);
    const upperBound = predictedAQI + horizonError;
    const confidenceScore = Math.max(68, Math.round(98 - (i / count) * 25));

    let trend: 'improving' | 'stable' | 'deteriorating' = 'stable';
    if (drift + diurnal < -6) trend = 'improving';
    else if (drift + diurnal > 6) trend = 'deteriorating';

    let primaryDriver = 'Normal boundary layer dispersion';
    if (hour >= 7 && hour <= 10) primaryDriver = 'Morning vehicular emission surge & surface inversion';
    else if (hour >= 13 && hour <= 16) primaryDriver = 'Peak photochemical oxidant formation (Solar UV)';
    else if (hour >= 18 && hour <= 21) primaryDriver = 'Evening commuter emissions and cooling wind stagnation';
    else if (i > 24) primaryDriver = 'Synoptic scale frontal system passage with turbulent mixing';

    points.push({
      timestamp: time.toISOString(),
      timeLabel:
        intervalHours === 24
          ? time.toLocaleDateString('en-US', { weekday: 'short', month: 'short', day: 'numeric' })
          : `${hour.toString().padStart(2, '0')}:00`,
      predictedAQI,
      lowerBound,
      upperBound,
      confidenceScore,
      dominantPollutant: predictedAQI > 80 ? 'pm25' : 'o3',
      primaryDriver,
      trend,
    });
  }

  return points;
}

