function generateHistorical24h(baseAQI: number): HistoricalReading[] {
  const readings: HistoricalReading[] = [];
  const now = new Date('2026-10-11T12:00:00+05:30');

  for (let i = 23; i >= 0; i--) {
    const time = new Date(now.getTime() - i * 60 * 60 * 1000);
    // Indian Standard Time hour
    const istHours = (time.getUTCHours() + 5.5) % 24;
    const hour = Math.floor(istHours);

    // Diurnal rush hour variations: morning peak around 8-10am IST, evening peak 7-9pm IST
    const diurnalFactor =
      1 +
      0.24 * Math.sin(((hour - 9) * Math.PI) / 12) +
      0.16 * Math.sin(((hour - 20) * Math.PI) / 8);
    const noise = Math.sin(i * 1.7) * 0.08;
    const aqi = Math.max(15, Math.round(baseAQI * diurnalFactor * (1 + noise)));

    const pm25 = parseFloat((aqi * 0.44 + Math.sin(i) * 3).toFixed(1));
    const pm10 = parseFloat((pm25 * 1.7 + Math.cos(i) * 5).toFixed(1));
    const no2 = parseFloat((aqi * 0.24 + Math.sin(i * 2) * 3).toFixed(1));
    const so2 = parseFloat((9.5 + Math.sin(i) * 2.2).toFixed(1));
    const co = parseFloat((0.8 + (aqi / 180) * 0.6).toFixed(2));
    const o3 = parseFloat((32 + Math.sin(((hour - 14) * Math.PI) / 12) * 24).toFixed(1));

    readings.push({
      timestamp: time.toISOString(),
      timeLabel: `${hour.toString().padStart(2, '0')}:00 IST`,
      aqi,
      pm25,
      pm10,
      no2,
      so2,
      co,
      o3,
      temperature: Math.round(24 + Math.sin(((hour - 14) * Math.PI) / 12) * 5),
      humidity: Math.round(62 + Math.cos(((hour - 14) * Math.PI) / 12) * 18),
    });
  }

  return readings;
}

function generateForecastPoints(
  baseAQI: number,
  count: number,
  intervalHours: number = 1
): ForecastPoint[] {
  const points: ForecastPoint[] = [];
  const start = new Date('2026-10-11T13:00:00+05:30');

  for (let i = 0; i < count; i++) {
    const time = new Date(start.getTime() + i * intervalHours * 60 * 60 * 1000);
    const istHours = (time.getUTCHours() + 5.5) % 24;
    const hour = Math.floor(istHours);

    // Weather shift simulation
    const drift = Math.sin(i / 6) * 16 - i * 0.18;
    const diurnal = Math.sin(((hour - 9) * Math.PI) / 12) * 15;
    const predictedAQI = Math.max(18, Math.round(baseAQI + drift + diurnal));

    // Uncertainty grows with forecast horizon
    const horizonError = Math.round(5 + i * 0.75);
    const lowerBound = Math.max(10, predictedAQI - horizonError);
    const upperBound = predictedAQI + horizonError;
    const confidenceScore = Math.max(68, Math.round(98 - (i / count) * 25));

    let trend: 'improving' | 'stable' | 'deteriorating' = 'stable';
    if (drift + diurnal < -6) trend = 'improving';
    else if (drift + diurnal > 6) trend = 'deteriorating';

    let primaryDriver = 'Boundary layer ventilation (IMD Model)';
    if (hour >= 7 && hour <= 10) primaryDriver = 'Morning commuter surge & shallow nocturnal boundary layer';
    else if (hour >= 13 && hour <= 16) primaryDriver = 'Afternoon photochemical ozone surge under high solar radiation';
    else if (hour >= 18 && hour <= 21) primaryDriver = 'Evening traffic peak & cooling surface temperature inversion';
    else if (i > 24) primaryDriver = 'Synoptic wind pattern & regional crop residue biomass advection';

    points.push({
      timestamp: time.toISOString(),
      timeLabel:
        intervalHours === 24
          ? time.toLocaleDateString('en-IN', { weekday: 'short', month: 'short', day: 'numeric', timeZone: 'Asia/Kolkata' })
          : `${hour.toString().padStart(2, '0')}:00 IST`,
      predictedAQI,
      lowerBound,
      upperBound,
      confidenceScore,
      dominantPollutant: predictedAQI > 90 ? 'pm25' : 'pm10',
      primaryDriver,
      trend,
    });
  }

  return points;
}

